import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

const publicDir = new URL('../public/', import.meta.url);
const htmlFile = new URL('index.html', publicDir);
const hasFile = path => existsSync(new URL(path, publicDir));
const widths = [384, 576, 864];
const window = {};
runInNewContext(readFileSync(new URL('assets/toys.js', publicDir), 'utf8'), {
  window,
  location: { search: '' },
  URLSearchParams,
});

const { MODELS, PROMPTS } = window;
const media = Object.fromEntries(PROMPTS.map(prompt => [
  prompt.id,
  Object.fromEntries(MODELS.filter(model => prompt.runs[model.id]).map(model => {
    const name = `${prompt.id}/${model.id}`;
    return [model.id, { widths: widths.filter(width => hasFile(`covers/${name}-${width}.webp`)) }];
  })),
]));

// Match the gallery grid in public/index.html and the runtime sizes in gallery.js.
const columns = Math.min(MODELS.length, 3);
const mobileColumns = Math.min(columns, 2);
const gaps = (columns - 1) * 20;
const mobileGaps = (mobileColumns - 1) * 12;
const sizes = `(max-width: 760px) calc(${100 / mobileColumns}vw - ${(32 + mobileGaps) / mobileColumns}px), min(calc(${92 / columns}vw - ${gaps / columns}px), ${(1440 - gaps) / columns}px)`;
const first = PROMPTS[0];
const preloads = [];
for (const model of MODELS.slice(0, 2)) {
  const assets = media[first?.id]?.[model.id];
  if (!assets) continue;
  const cover = `covers/${first.id}/${model.id}`;
  const srcset = assets.widths.map(w => `${cover}-${w}.webp ${w}w`).concat(`${cover}.webp 1200w`).join(', ');
  const priority = preloads.length ? '' : ' fetchpriority="high"';
  preloads.push(`<link rel="preload" as="image"${priority} imagesrcset="${srcset}" imagesizes="${sizes}">`);
}

const begin = '<!-- Gallery media generated by scripts/prepare-gallery.mjs -->';
const end = '<!-- End gallery media -->';
const html = readFileSync(htmlFile, 'utf8');
const start = html.indexOf(begin), finish = html.indexOf(end);
if (start < 0 || finish < start) throw new Error('Gallery media markers are missing from public/index.html');
const replacement = [
  begin,
  ...preloads,
  `<script type="application/json" id="gallery-media">${JSON.stringify(media).replace(/</g, '\\u003c')}</script>`,
  end,
].join('\n');
const output = html.slice(0, start) + replacement + html.slice(finish + end.length);
if (process.argv.includes('--check')) {
  if (html !== output) throw new Error('Run node scripts/prepare-gallery.mjs to update gallery media.');
} else if (html !== output) {
  writeFileSync(htmlFile, output);
}
